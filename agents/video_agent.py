class VideoAgent:
    def __init__(self):
        # موجه النظام (System Prompt) الذي يبرمج عقل الوكيل
        self.system_prompt = """
أنت خبير محترف في صناعة محتوى الفيديو القصير الفيروسي (Reels/TikToks/Shorts) بمدة صارمة تتراوح بين 10 إلى 15 ثانية.
مهمتك الوحيدة هي هندسة أوامر (Prompt Engineering) تفصيلية تعتمد بالكامل على تقنية "شبكات الصور المتسلسلة" (Sequential Image Grids)، وتحديداً نظام الـ 20 لوحة (20-panel grid).

قواعد بناء السيناريو:
1. المفهوم الأساسي (Core Theme): يجب أن تركز الأفكار على التطور الزمني والتحولات الجوهرية (Chronological & Transformational Evolution). يشمل ذلك تطور البشر، نمو وتغير الحيوانات، أو التطور التكنولوجي للأشياء.
2. النمط البصري (Visual Style): دمج الخدع البصرية (Visual Illusions) والانتقالات الخاطفة جداً (Quick Transitions) لخلق إيقاع سريع يمنع المشاهد من التمرير.
3. الهيكل: يجب أن يوفر السيناريو وصفاً دقيقاً ومختصراً لكل لوحة من اللوحات الـ 20 لتوجيه نماذج توليد الصور بدقة.

يجب أن يكون المخرج النهائي بالهيكل التالي:
- [عنوان الريلز]: جذاب وقصير.
- [الفكرة العامة]: سطر واحد يشرح التحول.
- [الصوت/المؤثرات]: نوع الموسيقى أو المؤثرات الصوتية المطابقة للانتقالات السريعة.
- [أوامر توليد الصور للـ 20 لوحة]: وصف متسلسل (من اللوحة 1 إلى 20) يوضح التدرج في التطور بدقة.
"""

    def process_request(self, user_request, client=None):
        """
        تقوم هذه الدالة باستقبال طلب المستخدم وتوليد سيناريو الفيديو باستخدام الذكاء الاصطناعي.
        ملاحظة: إذا كنت تستخدم OpenAI أو Groq، يتم تمرير الـ client هنا.
        """
        # في حال تم ربط نموذج فعلي (مثل Groq أو OpenAI)، سيكون الكود كالتالي:
        if client:
            response = client.chat.completions.create(
                model="llama3-70b-8192", # أو النموذج الذي تستخدمه
                messages=[
                    {"role": "system", "content": self.system_prompt},
                    {"role": "user", "content": f"قم بإنشاء سيناريو فيديو بناءً على هذا الطلب: {user_request}"}
                ],
                max_tokens=1000
            )
            return response.choices[0].message.content
        else:
            # محاكاة مؤقتة إذا لم يتم تمرير الـ client
            return f"[محاكاة] تم توليد سيناريو لـ 20 لوحة متسلسلة بناءً على: {user_request}"